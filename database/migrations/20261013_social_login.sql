ALTER TABLE usuario
  ADD COLUMN USUARIO_LOGIN VARCHAR(32) NULL AFTER EMAIL,
  ADD UNIQUE KEY UQ_USUARIO_LOGIN (USUARIO_LOGIN);

CREATE TABLE identidad_proveedor (
  ID_IDENTIDAD BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_USUARIO BIGINT UNSIGNED NOT NULL,
  PROVEEDOR VARCHAR(20) NOT NULL,
  ID_SUBJECT VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  EMAIL_PROVEEDOR VARCHAR(254) NOT NULL,
  CREADO_EN DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (ID_IDENTIDAD),
  UNIQUE KEY UQ_IDENTIDAD_PROVEEDOR_SUBJECT (PROVEEDOR, ID_SUBJECT),
  KEY IDX_IDENTIDAD_USUARIO (ID_USUARIO),
  CONSTRAINT FK_IDENTIDAD_USUARIO
    FOREIGN KEY (ID_USUARIO) REFERENCES usuario (ID_USUARIO)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
