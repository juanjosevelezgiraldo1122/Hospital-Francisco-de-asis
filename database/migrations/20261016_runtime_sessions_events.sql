-- Adiciona suporte para sesiones persistentes y avisos de sincronizacion.
-- No elimina tablas ni registros existentes; puede ejecutarse mas de una vez.

USE hospital_francisco_asis;

CREATE TABLE IF NOT EXISTS app_session (
  ID_SESSION BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  ID_USUARIO BIGINT UNSIGNED NOT NULL,
  TOKEN_HASH CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  EXPIRES_AT DATETIME(3) NOT NULL,
  CREATED_AT DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (ID_SESSION),
  UNIQUE KEY UQ_APP_SESSION_TOKEN (TOKEN_HASH),
  KEY IDX_APP_SESSION_EXPIRY (EXPIRES_AT),
  KEY IDX_APP_SESSION_USER (ID_USUARIO),
  CONSTRAINT FK_APP_SESSION_USER FOREIGN KEY (ID_USUARIO)
    REFERENCES usuario (ID_USUARIO) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS sync_event (
  ID_EVENT BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  EVENT_TYPE VARCHAR(80) NOT NULL,
  CREATED_AT DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (ID_EVENT),
  KEY IDX_SYNC_EVENT_CREATED (CREATED_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
