  `CREADA_EN` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `BLOQUE_MEDICO_ACTIVO` tinyint GENERATED ALWAYS AS ((case when (`ESTADO` in (_utf8mb4'Pendiente',_utf8mb4'En curso')) then 1 else NULL end)) STORED,
  `BLOQUE_PACIENTE_ACTIVO` tinyint GENERATED ALWAYS AS ((case when (`ESTADO` in (_utf8mb4'Pendiente',_utf8mb4'En curso')) then 1 else NULL end)) STORED,
  PRIMARY KEY (`ID_CITA`),
  UNIQUE KEY `UQ_CITA_PACIENTE_MEDICO` (`ID_CITA`,`ID_PACIENTE`,`NUMERO_LICENCIA`),
  UNIQUE KEY `UQ_CITA_MEDICO_BLOQUE_ACTIVO` (`NUMERO_LICENCIA`,`FECHA_CITA`,`HORA_CITA`,`BLOQUE_MEDICO_ACTIVO`),
  UNIQUE KEY `UQ_CITA_PACIENTE_BLOQUE_ACTIVO` (`ID_PACIENTE`,`FECHA_CITA`,`HORA_CITA`,`BLOQUE_PACIENTE_ACTIVO`),
  KEY `IDX_CITA_PACIENTE_FECHA` (`ID_PACIENTE`,`FECHA_CITA`,`HORA_CITA`,`ESTADO`),
  KEY `IDX_CITA_MEDICO_FECHA` (`NUMERO_LICENCIA`,`FECHA_CITA`,`HORA_CITA`,`ESTADO`),
  KEY `IDX_CITA_SEDE_FECHA` (`ID_SEDE`,`FECHA_CITA`,`ESTADO`),
  KEY `FK_CITA_GESTIONADA_POR` (`GESTIONADA_POR`),
  KEY `FK_CITA_CANCELADA_POR` (`CANCELADA_POR`),
  CONSTRAINT `FK_CITA_CANCELADA_POR` FOREIGN KEY (`CANCELADA_POR`) REFERENCES `usuario` (`ID_USUARIO`),
  CONSTRAINT `FK_CITA_GESTIONADA_POR` FOREIGN KEY (`GESTIONADA_POR`) REFERENCES `usuario` (`ID_USUARIO`),
  CONSTRAINT `FK_CITA_MEDICO` FOREIGN KEY (`NUMERO_LICENCIA`) REFERENCES `medico` (`NUMERO_LICENCIA`),
  CONSTRAINT `FK_CITA_PACIENTE` FOREIGN KEY (`ID_PACIENTE`) REFERENCES `paciente` (`ID_USUARIO`),
  CONSTRAINT `FK_CITA_SEDE` FOREIGN KEY (`ID_SEDE`) REFERENCES `sede` (`ID_SEDE`),
  CONSTRAINT `CK_CITA_CANCELACION` CHECK (((`ESTADO` <> _utf8mb4'Cancelada') or (`CANCELACION_EN` is not null))),
  CONSTRAINT `CK_CITA_ESTADO` CHECK ((`ESTADO` in (_utf8mb4'Pendiente',_utf8mb4'En curso',_utf8mb4'Finalizada',_utf8mb4'Cancelada'))),
  CONSTRAINT `CK_CITA_FINALIZACION` CHECK (((`ESTADO` <> _utf8mb4'Finalizada') or ((`INICIO_EN` is not null) and (`FINALIZACION_EN` is not null)))),
  CONSTRAINT `CK_CITA_INICIO` CHECK (((`ESTADO` <> _utf8mb4'En curso') or (`INICIO_EN` is not null))),
  CONSTRAINT `CK_CITA_TIEMPOS` CHECK (((`FINALIZACION_EN` is null) or (`INICIO_EN` is not null))),
  CONSTRAINT `CK_CITA_TIPO` CHECK ((`TIPO_ATENCION` in (_utf8mb4'general',_utf8mb4'especialista')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

